// ─── The second table: generated macros and the library boundary ────────────
//
// The 28 shapes above hold the macro fixed — hand-written, in the program —
// and move the use site's *binder*. This table holds the binder simple and
// moves the macro: who wrote it, and where. Those were the two axes the header
// used to list first among the uncovered ones, and issue #402 (chibi-tar) was
// both at once: a macro *generated by another macro* inside a library, then
// *imported*, lost every reference its template made to the library's own
// bindings. It has its own table rather than new `Site`s above because its
// axes do not cross with a `Binder`: a macro in a library cannot also be
// defined inside the use site's `let`.

/// How the macro `m` that mentions `X` came to exist.
#[derive(Clone, Copy, PartialEq)]
enum Maker {
    /// Hand-written: `(define-syntax m (syntax-rules () …))`. The control —
    /// one level of macro, which is all the first table has.
    Written,
    /// Generated: `(def-m m)`, where `def-m`'s template is the whole
    /// `define-syntax`, the mention of `X` included. `X` reaches `m`'s
    /// template as an identifier `def-m`'s expansion introduced.
    Generated,
    /// Generated, with the mention arriving through `def-m`'s pattern
    /// variable: `(def-m m X)`. `X` reaches `m`'s template as what the
    /// *caller* of `def-m` wrote — a different route through the template
    /// compiler from [`Maker::Generated`], and the one `chibi-binary-record`
    /// takes.
    GeneratedArg,
    /// Generated by a generator that **also introduces the definition the
    /// macro mentions**: `(def-m m get-X)` expands to `(define X 'def)`, a
    /// getter for it under the caller's name, and the `define-syntax` — the
    /// ordinary shape of a definer with private state. The binder is a
    /// macro-introduced global, which is triage family 40's axis; every other
    /// maker leaves `X` a definition somebody wrote. Here it is the only
    /// thing of its spelling at the definition site, so the bare name reaches
    /// it too, and relinking by name is enough.
    Introducing,
    /// [`Maker::Introducing`] with a plain `(define X 'plain)` beside it, so
    /// the bare name reaches *that* and only the mention's scopes select the
    /// introduced one. #408's first shape.
    IntroducingBeside,
    /// [`Maker::Introducing`] with the generator run a second time — the
    /// ordinary way to use a definer. The row uses the *first* run's macro and
    /// getter; the bare name reaches the second run's definition, which holds
    /// `'other` so that a read can tell the two apart. #408's second shape.
    IntroducingTwice,
    /// [`Maker::IntroducingTwice`] with both runs in **one top-level form**,
    /// as a macro that expands to two definer calls leaves them. The
    /// difference is the VM's: it renames and records introduced definitions
    /// a form at a time, and kept one record per *spelling* per form, so the
    /// first run's identity was lost and its macro was relinked by name — to
    /// the second run's `X`, silently. Two forms never showed it.
    IntroducingTogether,
}

impl Maker {
    /// Whether the generator introduces `X` itself, rather than mentioning
    /// one the definition site wrote.
    fn introduces(self) -> bool {
        matches!(
            self,
            Maker::Introducing
                | Maker::IntroducingBeside
                | Maker::IntroducingTwice
                | Maker::IntroducingTogether
        )
    }
}

/// What `m`'s template does with `X`.
#[derive(Clone, Copy, PartialEq)]
enum Mention {
    /// `X` is a variable and the template reads it.
    Read,
    /// `X` is a variable and the template assigns it.
    Write,
    /// `X` is a macro and the template uses it.
    Keyword,
}

/// Where `m` is defined, relative to where it is used.
#[derive(Clone, Copy, PartialEq)]
enum Boundary {
    /// In the program that uses it.
    Program,
    /// In a library that exports `m` and keeps `X` private, so the use site
    /// has no way to mean the library's `X` except through `m`.
    Library,
}

/// What the use site itself means by `X`.
///
/// This is the axis that makes the table two-directional. `Unbound` is the
/// loud face of #402 — the template's `X` reaches nothing. The other two are
/// the silent one: the use site has an `X` of its own, the template's must
/// not reach *it*, and the `X` the user passes to `m` as an argument must not
/// be dragged to the definition site either (Larceny family 35, which is the
/// direction a careless fix for the first face breaks).
#[derive(Clone, Copy, PartialEq)]
enum UseSite {
    /// The use site does not bind `X`.
    Unbound,
    /// The use site binds `X` at top level. Only under [`Boundary::Library`]:
    /// in one program that is a second definition of the *same* variable,
    /// which is not a question about hygiene.
    Global,
    /// The use site binds `X` in a `let` (`let-syntax` for a keyword).
    Local,
    /// The use site **imports** `X` from the library — so the two mean one
    /// binding while `m` is expanded — and defines an `X` of its own
    /// *afterwards* (#438). The expansion sits in a procedure that runs after
    /// the definition, as under [`Values::Equal`].
    ///
    /// R7RS calls redefining an import an error in a program and says a REPL
    /// should permit it; chibi and Gauche both permit it and both keep the
    /// template's `X` the library's. What they *disagree* about is a
    /// reference the program itself wrote before its definition (chibi keeps
    /// the import, Gauche follows the definition), so the row passes `m` a
    /// literal rather than the program's `X`.
    Redefined,
}

/// What the two `X`s hold **while the macro is being expanded**.
///
/// The axis #407 was missing, and the reason this table read 45 of 45 across
/// it: every row gave the two sides different values, and the relinker's
/// fast path compared values. Two variables that are both `0`, `#f` or `'()`
/// — which is what variables are initialised to — read as one binding, so a
/// library macro's `(set! X …)` landed on the importing program's `X`.
///
/// An `Equal` program cannot be the `Distinct` one with the values changed,
/// because a read of two equal values says nothing about which was read. So
/// it expands `m` inside a procedure while both sides hold `'same`, gives the
/// use site's `X` the value `'use` afterwards, and only then runs it. That
/// wrapper is how the axis is observed rather than a second thing it moves:
/// what differs at expansion time is the values and nothing else.
#[derive(Clone, Copy, PartialEq)]
enum Values {
    /// `'def` at the definition site, `'use` at the use site.
    Distinct,
    /// `'same` at both until `m` has been expanded.
    Equal,
}

/// One point in the second space.
struct MadeShape {
    maker: Maker,
    mention: Mention,
    boundary: Boundary,
    use_site: UseSite,
    values: Values,
    /// What chibi 0.12 and Gauche 0.9.15 both answer.
    correct: &'static str,
    /// What the VM answers today.
    vm: &'static str,
    /// What the tree-walker answers today.
    tw: &'static str,
    /// The defect this row is a face of, or `""` when the row is correct.
    family: &'static str,
}

impl MadeShape {
    fn name(&self) -> String {
        let maker = match self.maker {
            Maker::Written => "written",
            Maker::Generated => "generated",
            Maker::GeneratedArg => "generated-arg",
            Maker::Introducing => "introducing",
            Maker::IntroducingBeside => "introducing-beside",
            Maker::IntroducingTwice => "introducing-twice",
            Maker::IntroducingTogether => "introducing-together",
        };
        let mention = match self.mention {
            Mention::Read => "read",
            Mention::Write => "write",
            Mention::Keyword => "keyword",
        };
        let boundary = match self.boundary {
            Boundary::Program => "program",
            Boundary::Library => "library",
        };
        let use_site = match self.use_site {
            UseSite::Unbound => "unbound",
            UseSite::Global => "global",
            UseSite::Local => "local",
            UseSite::Redefined => "redefined",
        };
        let values = match self.values {
            Values::Distinct => "",
            Values::Equal => "/equal",
        };
        format!("{maker}/{mention}/{boundary}/{use_site}{values}")
    }
}

/// The two halves of a [`MadeShape`]'s program: the library form, when there
/// is one, and everything after it.
///
/// Kept apart because chibi cannot take a `define-library` in a script
/// (`tests/scheme/expansion/template-references.scm` has the measurement), so
/// [`dump_programs`] writes the first half to `hm/gen.sld` for the oracles.
/// Patina runs the two concatenated. Neither half is edited on the way.
///
/// Every shape observes both sides, like the first table: the definition
/// site's `X` through `get-X`, which the defining context supplies whether or
/// not the shape needs it (an axis must move one thing), and the use site's
/// through the argument the user passes to `m`. A write is sequenced by a
/// `let`, not by operand order, for the reason [`program`] gives.
fn made_program_parts(shape: &MadeShape) -> (Option<String>, String) {
    let equal = shape.values == Values::Equal;
    // `Equal` is an axis of two *variables*: a keyword holds no value to be
    // equal, and an unbound use site has no `X` to be equal with. Either
    // would build a program that runs and says nothing about the axis, so a
    // row asking for one is refused rather than scored.
    assert!(
        !equal || (shape.mention != Mention::Keyword && shape.use_site != UseSite::Unbound),
        "{}: `Values::Equal` needs a variable `X` on both sides",
        shape.name()
    );
    // Defining over an import takes a library to import from, a variable to
    // define, and an `X` the library can export by its bare name — which a
    // definition a macro introduced is not.
    let redefined = shape.use_site == UseSite::Redefined;
    assert!(
        !redefined
            || (shape.boundary == Boundary::Library
                && shape.mention != Mention::Keyword
                && !shape.maker.introduces()
                && !equal),
        "{}: `UseSite::Redefined` needs a library exporting a written variable `X`",
        shape.name()
    );
    // An introducing generator's `X` is a variable; a keyword it introduced
    // would be #269's `define-syntax` half, which is not this table's.
    assert!(
        !shape.maker.introduces() || (shape.mention != Mention::Keyword && !equal),
        "{}: an introducing maker needs a variable `X`, with distinct values",
        shape.name()
    );
    // What each side's variable starts as is all `Values` changes in the
    // definitions; the wrapper below is how it is observed.
    let (def_x, use_global, use_local) = if equal {
        ("(define X 'same)", "(define X 'same)", "let ((X 'same))")
    } else {
        ("(define X 'def)", "(define X 'use)", "let ((X 'use))")
    };
    let (define_x, mention, get_x) = match shape.mention {
        Mention::Read => (def_x, "X", "X"),
        Mention::Write => (def_x, "(set! X 'set)", "X"),
        Mention::Keyword => (
            "(define-syntax X (syntax-rules () ((X) 'def)))",
            "(X)",
            "(X)",
        ),
    };
    // What `m` expands to, given the text that mentions `X`.
    let template = |mention: &str| match shape.mention {
        Mention::Write => format!("(begin {mention} v)"),
        Mention::Read | Mention::Keyword => format!("(list {mention} v)"),
    };
    let make_m = match shape.maker {
        Maker::Written => format!(
            "(define-syntax m (syntax-rules () ((m v) {})))",
            template(mention)
        ),
        Maker::Generated => format!(
            "(define-syntax def-m\n  (syntax-rules ()\n    ((def-m name)\n     \
             (define-syntax name (syntax-rules () ((name v) {}))))))\n(def-m m)",
            template(mention)
        ),
        Maker::GeneratedArg => format!(
            "(define-syntax def-m\n  (syntax-rules ()\n    ((def-m name mention)\n     \
             (define-syntax name (syntax-rules () ((name v) {}))))))\n(def-m m {mention})",
            template("mention")
        ),
        // The definer alone; what runs it, and how often, is the rest of the
        // axis, below. It takes the value so that two runs can differ.
        Maker::Introducing
        | Maker::IntroducingBeside
        | Maker::IntroducingTwice
        | Maker::IntroducingTogether => format!(
            "(define-syntax def-m\n  (syntax-rules ()\n    ((def-m name getter value)\n     \
             (begin\n       (define X value)\n       (define (getter) {get_x})\n       \
             (define-syntax name (syntax-rules () ((name v) {})))))))",
            template(mention)
        ),
    };
    // The definition site's `X` and its getter are the generator's own work
    // under an introducing maker; what stands beside them is the rest of the
    // axis.
    let (first_run, second_run) = ("(def-m m get-X 'def)", "(def-m m2 get-X2 'other)");
    let definitions = match shape.maker {
        Maker::Introducing => format!("{make_m}\n{first_run}"),
        Maker::IntroducingBeside => format!("(define X 'plain)\n{make_m}\n{first_run}"),
        Maker::IntroducingTwice => format!("{make_m}\n{first_run}\n{second_run}"),
        Maker::IntroducingTogether => format!("{make_m}\n(begin {first_run} {second_run})"),
        Maker::Written | Maker::Generated | Maker::GeneratedArg => {
            format!("{define_x}\n(define (get-X) {get_x})\n{make_m}")
        }
    };

    // The use site's own `X`, and the expression that names it.
    let (bind_global, bind_local, own_x) = match shape.mention {
        Mention::Read | Mention::Write => (use_global, use_local, "X"),
        Mention::Keyword => (
            "(define-syntax X (syntax-rules () ((X) 'use)))",
            "let-syntax ((X (syntax-rules () ((X) 'use))))",
            "(X)",
        ),
    };
    let own_x = if matches!(shape.use_site, UseSite::Unbound | UseSite::Redefined) {
        "'use"
    } else {
        own_x
    };
    let observe = match shape.mention {
        Mention::Write => format!("(let ((u (m {own_x}))) (list (get-X) u))"),
        Mention::Read | Mention::Keyword => format!("(m {own_x})"),
    };
    // Under `Values::Equal`: expand while the two are equal, tell them apart,
    // then run. Each top-level form is expanded as it is reached, so the
    // `define` is expanded before the `set!` runs; a `let` body is expanded
    // whole, before any of it runs.
    let use_site = match (shape.use_site, equal) {
        (UseSite::Unbound, _) => observe,
        // Expand while `X` is the import, define over it, then run.
        (UseSite::Redefined, _) => {
            format!("(define (run) {observe})\n{bind_global}\n(run)")
        }
        (UseSite::Global, false) => format!("{bind_global}\n{observe}"),
        (UseSite::Local, false) => format!("({bind_local} {observe})"),
        (UseSite::Global, true) => {
            format!("{bind_global}\n(define (run) {observe})\n(set! X 'use)\n(run)")
        }
        (UseSite::Local, true) => {
            format!("({bind_local} (define (run) {observe}) (set! X 'use) (run))")
        }
    };

    match shape.boundary {
        Boundary::Program => (None, format!("{definitions}\n{use_site}")),
        Boundary::Library => {
            let body = definitions.replace('\n', "\n    ");
            let exports = if redefined { "m get-X X" } else { "m get-X" };
            let library = format!(
                "(define-library (hm gen)\n  (import (scheme base))\n  \
                 (export {exports})\n  (begin\n    {body}))"
            );
            (
                Some(library),
                format!("(import (scheme base) (hm gen))\n{use_site}"),
            )
        }
    }
}

/// The program Patina runs for one [`MadeShape`].
fn made_program(shape: &MadeShape) -> String {
    match made_program_parts(shape) {
        (Some(library), main) => format!("{library}\n{main}"),
        (None, main) => main,
    }
}

