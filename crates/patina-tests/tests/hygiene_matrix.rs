/// Where the macro that mentions `X` is defined, relative to the binding of
/// `X` at the use site.
///
/// This is the axis that decides which way hygiene must point, and the axis
/// PR #138 got half right: a template's `X` means the binding visible **where
/// the macro was written**, so a macro defined outside must reach *past* a
/// same-named use-site binder, and one defined inside must reach *into* it.
#[derive(Clone, Copy, PartialEq)]
enum Site {
    /// Top level, so the template's `X` is the global.
    Outside,
    /// Inside the binding form, so the template's `X` is the binder's.
    Inside,
}

/// What the template does with `X`.
#[derive(Clone, Copy, PartialEq)]
enum Action {
    Read,
    Write,
}

/// How the use site binds `X`.
///
/// An enum rather than a string key, so a typo is a compile error as it
/// already is for [`Site`] and [`Action`]. As a `&str` matched with a
/// `panic!` default, a misspelled binder still produced a row that two of the
/// tests counted as valid before the third panicked on it.
#[derive(Clone, Copy, PartialEq)]
enum Binder {
    LambdaParam,
    Let,
    LetStar,
    Letrec,
    NamedLet,
    InternalDef,
    DoVar,
}

impl Binder {
    fn name(self) -> &'static str {
        match self {
            Binder::LambdaParam => "lambda-param",
            Binder::Let => "let",
            Binder::LetStar => "let*",
            Binder::Letrec => "letrec",
            Binder::NamedLet => "named-let",
            Binder::InternalDef => "internal-def",
            Binder::DoVar => "do-var",
        }
    }
}

/// One point in the space.
struct Shape {
    /// How the use site binds `X`.
    binder: Binder,
    site: Site,
    action: Action,
    /// What chibi 0.12 and Racket 9.3 both answer.
    correct: &'static str,
    /// What the VM answers today.
    vm: &'static str,
    /// What the tree-walker answers today.
    tw: &'static str,
    /// The defect this row is a face of, or `""` when the row is correct.
    family: &'static str,
}

/// Wrap `body` in a binding of `X` to 5.
///
/// Every form R7RS gives for binding a variable at a use site, since the
/// question "does a template's reference get captured" is about the *binding*,
/// not about which surface form produced it — and the answer turned out to
/// differ between them (an internal define behaves unlike a `let`).
fn binder_expr(binder: Binder, body: &str) -> String {
    match binder {
        Binder::LambdaParam => format!("((lambda (X) {body}) 5)"),
        Binder::Let => format!("(let ((X 5)) {body})"),
        Binder::LetStar => format!("(let* ((X 5)) {body})"),
        Binder::Letrec => format!("(letrec ((X 5)) {body})"),
        Binder::NamedLet => format!("(let lp ((X 5)) {body})"),
        Binder::InternalDef => format!("((lambda () (define X 5) {body}))"),
        Binder::DoVar => format!("(do ((X 5 X)) (#t {body}))"),
    }
}

/// Build the program for one shape.
///
/// Both the inner result and the global are observed, because a capture shows
/// up in either one depending on direction, and reporting only one hides half
/// the defect. Order is forced through `(define r …)` rather than written as
/// `(list (f) X)`: R7RS §4.1.3 leaves operand order unspecified, and a
/// version of this matrix that did not force it read chibi's right-to-left
/// evaluation as a divergence.
fn program(shape: &Shape) -> String {
    let template = match shape.action {
        Action::Read => "X",
        Action::Write => "(set! X 99)",
    };
    let macro_def = format!("(define-syntax m (syntax-rules () ((m) {template})))");
    // A write has to be observed after it happens, so the body yields `X`.
    let body = match shape.action {
        Action::Read => "(m)".to_string(),
        Action::Write => "(begin (m) X)".to_string(),
    };
    let inner = match shape.site {
        Site::Outside => binder_expr(shape.binder, &body),
        // `Site::Inside` must move the macro definition and nothing else. A
        // `do` result clause is a sequence of expressions, not a `⟨body⟩`
        // (R7RS §5.3.2), so putting a `define-syntax` there changes *two*
        // things and both oracles reject the program — which cost `do-var`
        // its inside-direction hygiene coverage entirely, two of 28 cells
        // measuring a definition-context defect instead. `(let () …)` supplies
        // the definition context without binding anything, so the axis moves
        // one thing again. The definition-context defect keeps its own test.
        Site::Inside if shape.binder == Binder::DoVar => {
            binder_expr(shape.binder, &format!("(let () {macro_def} {body})"))
        }
        Site::Inside => binder_expr(shape.binder, &format!("{macro_def} {body}")),
    };
    match shape.site {
        Site::Outside => format!("(define X 'global)\n{macro_def}\n(define r {inner})\n(list r X)"),
        Site::Inside => format!("(define X 'global)\n(define r {inner})\n(list r X)"),
    }
}

