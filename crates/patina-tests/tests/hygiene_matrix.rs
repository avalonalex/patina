/// Write every program out, **ready to run** under an oracle.
///
/// Ignored by default: it asserts nothing, it exists so both tables can be
/// re-*measured* rather than re-derived — the same arrangement, for the same
/// reason, as `control_flow_matrix.rs`'s `dump_programs`. The text an oracle
/// is fed must be the text this file runs, and taking it from the same
/// generator is the only thing that guarantees it.
///
/// Each shape gets a directory holding `main.scm` — the program behind an
/// `(import (scheme base) (scheme write))`, with a `write` around its final
/// expression, which the oracles otherwise evaluate silently — and, for a
/// [`Boundary::Library`] shape, the library form verbatim in `hm/gen.sld`,
/// since chibi cannot take one in a script. **The program text itself is
/// never edited.**
///
/// ```text
/// HYGIENE_MATRIX_DUMP=/tmp/hm cargo test -p patina-tests \
///     --test hygiene_matrix -- --ignored dump_programs
/// for d in /tmp/hm/*/; do chibi-scheme -I "$d" "$d/main.scm"; done
/// for d in /tmp/hm/*/; do gosh -r7 -I "$d" "$d/main.scm"; done
/// ```
#[test]
#[ignore]
fn dump_programs() {
    let dir = std::env::var("HYGIENE_MATRIX_DUMP").expect("set HYGIENE_MATRIX_DUMP to a directory");
    let first = MATRIX.iter().map(|s| (s.name(), None, program(s)));
    let second = MADE.iter().map(|s| {
        let (library, main) = made_program_parts(s);
        (s.name(), library, main)
    });
    for (name, library, main) in first.chain(second) {
        let sub = format!("{dir}/{}", name.replace('/', "_").replace('*', "star"));
        std::fs::create_dir_all(format!("{sub}/hm")).expect("create dump directory");
        if let Some(library) = library {
            std::fs::write(format!("{sub}/hm/gen.sld"), format!("{library}\n"))
                .expect("write library");
        }
        let (body, last) = main
            .rsplit_once('\n')
            .expect("every program has more than one line");
        std::fs::write(
            format!("{sub}/main.scm"),
            format!("(import (scheme base) (scheme write))\n{body}\n(write {last})(newline)\n"),
        )
        .expect("write program");
    }
}

/// A row of either table, reduced to what scoring reads.
struct Row {
    name: String,
    code: String,
    correct: &'static str,
    vm: &'static str,
    tw: &'static str,
    family: &'static str,
}

/// Both tables, so the scoring tests cannot cover one and forget the other.
fn all_rows() -> Vec<Row> {
    let first = MATRIX.iter().map(|s| Row {
        name: s.name(),
        code: program(s),
        correct: s.correct,
        vm: s.vm,
        tw: s.tw,
        family: s.family,
    });
    let second = MADE.iter().map(|s| Row {
        name: s.name(),
        code: made_program(s),
        correct: s.correct,
        vm: s.vm,
        tw: s.tw,
        family: s.family,
    });
    first.chain(second).collect()
}

/// Run one shape on one backend, rendering a rejection as [`ERROR`].
fn answer(code: &str, vm: bool) -> String {
    let ok = if vm {
        try_eval_program_vm(code)
    } else {
        try_eval_program_tree_walker(code)
    };
    // The message is kept rather than collapsed to a token: no row expects an
    // error, so one appearing is a surprise, and a bare `<error>` in the
    // failure output would say nothing about which.
    ok.unwrap_or_else(|e| format!("{ERROR}: {}", e.lines().next().unwrap_or("").trim()))
}

/// Every shape answers what the table says it answers, on both backends.
///
/// The whole point is that this fails in *both* directions: fixing a defect
/// turns its row red just as breaking a working shape does. A red row is never
/// "just update the table" — read which direction it moved first.
#[test]
fn shapes_score_as_recorded() {
    let mut moved = Vec::new();
    for row in all_rows() {
        for (backend, recorded) in [("vm", row.vm), ("tree-walker", row.tw)] {
            let got = answer(&row.code, backend == "vm");
            if got != recorded {
                moved.push(common::describe_move(
                    &row.name,
                    backend,
                    recorded,
                    &got,
                    row.correct,
                    &row.code,
                ));
            }
        }
    }
    assert!(
        moved.is_empty(),
        "{} hygiene shape(s) no longer answer what the matrix records.\n\n{}\n\n\
         Update the row(s) in MATRIX or MADE and the count in \
         `the_defect_count_is_what_the_roadmap_says`, then say which family \
         moved in {TRIAGE}.",
        moved.len(),
        moved.join("\n\n")
    );
}

/// How many shapes each backend gets wrong, asserted as a number.
///
/// A count is the thing the chibi suite cannot give: it has read 1226/1226 on
/// both backends through every defect in this table. This number can only move
/// deliberately.
#[test]
fn the_defect_count_is_what_the_roadmap_says() {
    let rows = all_rows();
    let wrong = |pick: fn(&Row) -> &'static str| {
        rows.iter()
            .filter(|r| pick(r) != r.correct)
            .map(|r| r.name.clone())
            .collect::<Vec<_>>()
    };
    let vm = wrong(|r| r.vm);
    let tw = wrong(|r| r.tw);

    // Zero, on both backends and in both tables — the hygiene queue's steps 1
    // and 2 are done, and family 47's eighteen rows (36 cells) went green
    // together. A row going red now is a regression on a shape the oracles
    // agree about, whichever direction it moved.
    assert_eq!(vm.len(), 0, "VM shapes wrong: {vm:?}");
    assert_eq!(tw.len(), 0, "tree-walker shapes wrong: {tw:?}");

    // Every wrong row names the family it belongs to, so the table doubles as
    // the index from defect to surface count.
    for row in &rows {
        let correct = row.vm == row.correct && row.tw == row.correct;
        assert_eq!(
            correct,
            row.family.is_empty(),
            "{}: `family` must be set exactly on rows some backend gets wrong",
            row.name
        );
    }
}

