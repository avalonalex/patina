impl Shape {
    fn name(&self) -> String {
        let site = if self.site == Site::Outside {
            "outside"
        } else {
            "inside"
        };
        let action = if self.action == Action::Read {
            "read"
        } else {
            "write"
        };
        format!("{}/{site}/{action}", self.binder.name())
    }
}

/// Run one shape on one backend, rendering a rejection as [`ERROR`].
fn answer(code: &str, vm: bool) -> String {
    let ok = if vm {
        try_eval_program_vm(code)
    } else {
        try_eval_program_tree_walker(code)
    };
    // The message is kept rather than collapsed to a token: no row expects an
    // error, so one appearing is a surprise, and a bare `<error>` in the
    // failure output would say nothing about which.
    ok.unwrap_or_else(|e| format!("{ERROR}: {}", e.lines().next().unwrap_or("").trim()))
}

/// Every shape answers what the table says it answers, on both backends.
///
/// The whole point is that this fails in *both* directions: fixing a defect
/// turns its row red just as breaking a working shape does. A red row is never
/// "just update the table" — read which direction it moved first.
#[test]
fn shapes_score_as_recorded() {
    let mut moved = Vec::new();
    for shape in MATRIX {
        let code = program(shape);
        for (backend, recorded) in [("vm", shape.vm), ("tree-walker", shape.tw)] {
            let got = answer(&code, backend == "vm");
            if got != recorded {
                let direction = if got == shape.correct {
                    "FIXED — it now matches chibi and Racket"
                } else if recorded == shape.correct {
                    "REGRESSED — it used to match chibi and Racket"
                } else {
                    "changed, and is still wrong"
                };
                moved.push(format!(
                    "  {} [{backend}] {direction}\n    recorded {recorded}\n    got      {got}\n\
                     \x20   correct  {}\n    program:\n{}",
                    shape.name(),
                    shape.correct,
                    code.lines()
                        .map(|l| format!("      {l}"))
                        .collect::<Vec<_>>()
                        .join("\n")
                ));
            }
        }
    }
    assert!(
        moved.is_empty(),
        "{} hygiene shape(s) no longer answer what the matrix records.\n\n{}\n\n\
         Update the row(s) in MATRIX and the count in \
         `the_defect_count_is_what_the_roadmap_says`, then say which family \
         moved in {TRIAGE}.",
        moved.len(),
        moved.join("\n\n")
    );
}

/// How many shapes each backend gets wrong, asserted as a number.
///
/// A count is the thing the chibi suite cannot give: it has read 1226/1226 on
/// both backends through every defect in this table. This number can only move
/// deliberately.
#[test]
fn the_defect_count_is_what_the_roadmap_says() {
    let wrong = |pick: fn(&Shape) -> &'static str| {
        MATRIX
            .iter()
            .filter(|s| pick(s) != s.correct)
            .map(|s| s.name())
            .collect::<Vec<_>>()
    };
    let vm = wrong(|s| s.vm);
    let tw = wrong(|s| s.tw);

    // VM: an internal define captures a template's reference in both
    // directions — family 36's only VM surface.
    assert_eq!(vm.len(), 2, "VM shapes wrong: {vm:?}");
    // Tree-walker: family 36 on all seven binders in the read direction, and
    // family 38's fallback on the internal define.
    assert_eq!(tw.len(), 8, "tree-walker shapes wrong: {tw:?}");

    // Every wrong row names the family it belongs to, so the table doubles as
    // the index from defect to surface count.
    for shape in MATRIX {
        let correct = shape.vm == shape.correct && shape.tw == shape.correct;
        assert_eq!(
            correct,
            shape.family.is_empty(),
            "{}: `family` must be set exactly on rows some backend gets wrong",
            shape.name()
        );
    }
}

/// Family 36 is one defect with eight surfaces, not eight defects.
///
/// Recorded as a test rather than as prose because the count is what makes the
/// fix's acceptance criterion checkable: all seven go green together, or the
/// fix is addressing a symptom.
#[test]
fn family_36_has_eight_surfaces() {
    let faces: Vec<String> = MATRIX
        .iter()
        .filter(|s| s.family == "36")
        .map(|s| s.name())
        .collect();
    assert_eq!(faces.len(), 8, "{faces:?}");
    // Seven are the read direction, one per binder; the eighth is the write
    // direction through an internal define, which only the VM gets wrong.
    assert_eq!(
        faces
            .iter()
            .filter(|n| n.ends_with("/outside/read"))
            .count(),
        7,
        "{faces:?}"
    );
}

/// The two `do` rows are not a hygiene defect and should not be fixed as one.
///
/// R7RS §5.3.2 admits definitions in a `⟨body⟩`; a `do` result clause is a
/// sequence of expressions, not a body. chibi and Racket both reject it and
/// Patina runs it. Separated from the hygiene rows because a reader scanning
/// this file for "what is wrong with our macros" should not count it.
#[test]
fn a_do_result_clause_is_not_a_definition_context() {
    let code = "(define X 'global)\n\
                (define r (do ((X 5 X)) (#t (define-syntax m (syntax-rules () ((m) X))) (m))))\n\
                (list r X)";
    // Pinned as accepted, which is the defect. When Patina starts rejecting
    // this, both of these turn red and the two `do` rows in MATRIX get
    // `vm`/`tw` set to ERROR.
    assert_eq!(eval_program_vm(code), "(5 global)");
    assert_eq!(eval_program_tree_walker(code), "(5 global)");
}
