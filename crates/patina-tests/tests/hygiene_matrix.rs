//! A generated matrix of macro-hygiene shapes, scored against two reference
//! implementations.
//!
//! Hygiene defects in this repo have been found one at a time, by accident —
//! a corpus package tripping over one, a review noticing another. That is how
//! triage families 33–38 arrived, and it has a failure mode: a fix aimed at
//! one shape silently breaks the *opposite* shape, because nothing enumerates
//! the opposite shape. PR #133 and PR #138 were both closed for exactly that,
//! after passing every gate in the repo including 1226/1226 on the chibi
//! suite.
//!
//! So this file does not test a defect. It enumerates a **space** — the cross
//! product of how a use site binds a name, where the macro that mentions that
//! name is defined, and whether the template reads or assigns it — and pins
//! what each backend answers for every point in it. A fix that improves one
//! row and breaks another cannot pass.
//!
//! # The oracle
//!
//! The `correct` column is what **chibi 0.12 and Racket 9.3 both** answer,
//! measured 2026-08-28. They agree on all 28 shapes, which is why a single
//! column can stand for "correct". Patina gets **9** of the 28 wrong — two on
//! the VM, eight on the tree-walker, one of them on both.
//!
//! Every shape is a program both oracles *accept*: see the note in
//! **Adding axes** about why a row pinned at "both reject it" is not coverage.
//! The one shape Patina accepts and both oracles reject has its own test,
//! [`a_do_result_clause_is_not_a_definition_context`], because it is a
//! definition-context defect rather than a hygiene one and should not be
//! counted with these.
//!
//! Two independent implementations agreeing is the strongest oracle available
//! here; R7RS §4.3.2 states referential transparency but does not work these
//! shapes out.
//!
//! # Reading a row
//!
//! Each row records `correct`, and what the VM and the tree-walker answer
//! **today**. A row where an actual differs from `correct` is a live defect,
//! pinned so it cannot drift silently. [`shapes_score_as_recorded`] asserts
//! every actual, so:
//!
//! - **fix a defect** → its row goes red with `left` = the new (correct)
//!   answer. Update that row's `vm`/`tw` to match and the count in
//!   [`the_defect_count_is_what_the_roadmap_says`].
//! - **break a working shape** → its row goes red too. That is the direction
//!   #138 went, undetected.
//!
//! # Adding axes
//!
//! The axes here are deliberately the cheap ones. The shapes this file does
//! *not* cover yet, roughly in order of how much they are worth: a macro
//! generated by another macro; a macro imported across a library boundary;
//! expansion nested more than one level; ellipsis depth greater than one;
//! `define-record-type` and other derived binding forms; and literals in the
//! pattern. Each is a new `Site` or `Binder`, not a new file.
//!
//! **An axis must move one thing.** `Site::Inside` originally placed the
//! macro definition wherever the binder's body went, which for `do` is the
//! result clause — a sequence of expressions, not a `⟨body⟩` (R7RS §5.3.2).
//! That moved the definition *and* made the program ill-formed, so both
//! oracles rejected it, two of the 28 cells measured a definition-context
//! defect instead of hygiene, and `do-var` had no inside-direction hygiene
//! coverage at all. Agreement on *rejection* is not agreement on an answer.
//! The definition-context defect has its own test; the matrix supplies a
//! `(let () …)` so the axis moves one thing again.

