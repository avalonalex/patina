//! A generated matrix of macro-hygiene shapes, scored against two reference
//! implementations.
//!
//! Hygiene defects in this repo have been found one at a time, by accident —
//! a corpus package tripping over one, a review noticing another. That is how
//! triage families 33–38 arrived, and it has a failure mode: a fix aimed at
//! one shape silently breaks the *opposite* shape, because nothing enumerates
//! the opposite shape. PR #133 and PR #138 were both closed for exactly that,
//! after passing every gate in the repo including 1226/1226 on the chibi
//! suite.
//!
//! So this file does not test a defect. It enumerates a **space** — the cross
//! product of how a use site binds a name, where the macro that mentions that
//! name is defined, and whether the template reads or assigns it — and pins
//! what each backend answers for every point in it. A fix that improves one
//! row and breaks another cannot pass.
//!
//! There are two tables. [`MATRIX`] is that cross product: 28 shapes that
//! hold the macro fixed — hand-written, in the program — and move the use
//! site's binder. [`MADE`] holds the binder simple and moves the *macro*: 109
//! shapes over how it came to exist (written, or generated by another macro),
//! where (the program, or a library that keeps `X` private), what its
//! template does with `X`, what the use site itself means by `X`, and — for
//! 18 of them — whether the two `X`s hold equal values while the macro is
//! expanded ([`Values`]). In 40 of them the generator also *introduces* the
//! `X` its macro mentions, so the binder is a macro-introduced global (the
//! `Introducing` makers). Both tables are scored by the same tests.
//!
//! # The oracle
//!
//! The `correct` column is what **chibi 0.12 and Racket 9.3 both** answer,
//! measured 2026-08-28. They agree on all 28 shapes, which is why a single
//! column can stand for "correct". Patina got **9** of the 28 wrong when
//! first measured — two on the VM, eight on the tree-walker, one of them on
//! both. The six ordinary-binder read rows went green together when the
//! by-name fallback stopped resurrecting a rejected binding (the triage
//! queue's step 1); the three internal-define rows went green together when
//! internal defines started carrying the scopes of the body they stand in to
//! the runtime (step 2). **All 28 now match the oracles.** The matrix stays:
//! every row is a regression guard now, in both directions, which is the
//! guard PR #133 and PR #138 did not have.
//!
//! Every shape is a program both oracles *accept*: see the note in
//! **Adding axes** about why a row pinned at "both reject it" is not coverage.
//! The one shape Patina accepts and both oracles reject has its own test,
//! [`a_do_result_clause_is_not_a_definition_context`], because it is a
//! definition-context defect rather than a hygiene one and should not be
//! counted with these.
//!
//! Two independent implementations agreeing is the strongest oracle available
//! here; R7RS §4.3.2 states referential transparency but does not work these
//! shapes out.
//!
//! [`MADE`]'s `correct` column is what **chibi 0.12 and Gauche 0.9.15 both**
//! answer, measured 2026-09-18 from [`dump_programs`]'s output; they agree on
//! all 45. Racket was not available for that measurement and is *not* claimed
//! for those rows. The same run re-measured [`MATRIX`] under both, and Gauche
//! agrees with the recorded column on all 28. Patina got **18** of the 45
//! wrong, on both backends — exactly the generated-macro rows across a
//! library boundary, with both controls (generated in one program;
//! hand-written across a library) clean. That is triage family 47, issue
//! #402, and all eighteen went green together.
//!
//! The 18 [`Values::Equal`] rows were measured the same way on 2026-09-19,
//! and chibi and Gauche agree on all of them. Patina got the **6** across a
//! library with a top-level `X` at the use site wrong, on both backends,
//! hand-written macros included — #407, a value comparison where a question
//! about the binding was needed — and they went green together when the
//! relinker started asking it. The 12 others were never wrong and are the
//! control: one program, where nothing is relinked, and a `let`-bound `X`,
//! which the by-name view being compared does not see.
//!
//! The 40 `Introducing` rows, same method, 2026-09-19, and chibi and Gauche
//! agree on all of them. Patina got **12** wrong on both backends — across a
//! library, with something else of the spelling at the definition site: a
//! plain `X`, or a second run of the generator. Eight of those were the loud
//! `unbound variable: X`; the four with a top-level `X` at the use site were
//! silent, the template reading and assigning the *program's*. That is #408:
//! the relinker aliased by name, and the name does not identify such a
//! definition. They went green together when the alias started naming the
//! binding the mention's scopes select. 18 others are the control — the
//! introduced `X` alone of its spelling, where the name is enough, and
//! everything in one program, where nothing is relinked.
//!
//! The last **10**, `introducing-together`, put the definer's two runs in one
//! top-level form, and were wrong on the **VM alone** — in one program as
//! well as across a library, and every one of them silently: the first run's
//! macro read and assigned the second run's `X`. Review of #408 found it. The
//! VM kept one record per *spelling* per form of the definitions it renamed,
//! so the first run's identity was never recorded (`RenameEnv::global_aliases`
//! in patina-vm). Two runs in two forms never showed it, which is what
//! `introducing-twice` had been measuring.
//!
//! The **6** `redefined` rows ([`UseSite::Redefined`]), same method, same
//! day, chibi and Gauche agreeing on all of them: the program imports `X`,
//! expands `m`, and *then* defines an `X` of its own. All six were wrong on
//! both backends, silently — a read answered `(use use)` and a write landed
//! on the program's `X` — and written macros as much as generated ones. That
//! is #438: where both sides reach one binding the relinker left the
//! template's reference as a bare global name, which is looked up when it
//! runs. It is bound to the import's location now.
//!
//! # Reading a row
//!
//! Each row records `correct`, and what the VM and the tree-walker answer
//! **today**. A row where an actual differs from `correct` is a live defect,
//! pinned so it cannot drift silently. [`shapes_score_as_recorded`] asserts
//! every actual, so:
//!
//! - **fix a defect** → its row goes red with `left` = the new (correct)
//!   answer. Update that row's `vm`/`tw` to match and the count in
//!   [`the_defect_count_is_what_the_roadmap_says`].
//! - **break a working shape** → its row goes red too. That is the direction
//!   #138 went, undetected.
//!
//! # Adding axes
//!
//! The axes here are deliberately the cheap ones. Two that this list used to
//! open with are [`MADE`]'s now — a macro generated by another macro, and a
//! macro imported across a library boundary — and each had produced a
//! both-backend defect found somewhere other than this file before it was an
//! axis: triage family 13 through `(r6rs enums)` (a pattern variable under
//! `quote`, substituted in a hand-written macro and not in a generated one;
//! pinned in `tests/scheme/expansion/syntax-rules.scm`), and family 47 through
//! the compat corpus's `chibi-tar`, which was both axes at once. The shapes
//! this file does *not* cover yet, roughly in order of how much they are
//! worth: expansion nested more than two levels; ellipsis depth greater than
//! one;
//! `define-record-type` and other derived binding forms; literals in the
//! pattern; and the *refusal* half of a **macro-introduced global** as the
//! binder — the family-40 shapes (the last section of
//! `tests/scheme/expansion/hygiene.scm`; the last three rows of
//! `larceny_families.rs` before #193 Phase 1 deleted it), where a reference
//! from a *different* expansion must not reach the definition, the two
//! backends currently diverge, and the tree-walker is the one chibi agrees
//! with (#427). The half where the reference *should* reach it is
//! [`MADE`]'s since #408: the `Introducing` makers, whose generated macro
//! mentions a definition its own generator introduced, in one program and
//! across a library. Each is a new `Site`, `Binder`, `Maker` or the like, not
//! a new file.
//!
//! **An axis must move one thing.** `Site::Inside` originally placed the
//! macro definition wherever the binder's body went, which for `do` is the
//! result clause — a sequence of expressions, not a `⟨body⟩` (R7RS §5.3.2).
//! That moved the definition *and* made the program ill-formed, so both
//! oracles rejected it, two of the 28 cells measured a definition-context
//! defect instead of hygiene, and `do-var` had no inside-direction hygiene
//! coverage at all. Agreement on *rejection* is not agreement on an answer.
//! The definition-context defect has its own test; the matrix supplies a
//! `(let () …)` so the axis moves one thing again.

