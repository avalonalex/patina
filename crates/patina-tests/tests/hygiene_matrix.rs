/// A program that defines over an imported name *after* a library macro
/// mentioning it was expanded does not capture the template's reference: one
/// procedure, compiled once, bumps the library's `count` on both of its
/// calls. chibi 0.12 and Gauche 0.9.15 both answer `(2 100)`.
///
/// This pinned `(1 101)` from #439 until #438: the second call bumped the
/// *program's* `count`. The relinker leaves a template's reference alone when
/// the use site and the definition site reach one binding by the name, and
/// here they truthfully do — the program's `count` *is* the import. Left
/// alone it was a bare global name, resolved again when it ran, and `define`
/// over an import makes the program a binding of its own in the same slot. It
/// is bound to the import's *location* now (`Environment::import_alias`).
///
/// [`MADE`]'s `redefined` rows score the axis. This test stays for the shape
/// they do not have — the same procedure called on both sides of the
/// definition — and for the other order, define first and expand afterwards,
/// which was always right and which a fix for one order must not cost.
#[test]
fn a_definition_over_an_import_does_not_capture_an_expanded_template() {
    let library = "(define-library (hm shared)\n  (import (scheme base))\n  \
                   (export count get-count bump-count!)\n  (begin\n    \
                   (define count 0)\n    (define (get-count) count)\n    \
                   (define-syntax bump-count!\n      \
                   (syntax-rules () ((_) (set! count (+ count 1)))))))\n\
                   (import (scheme base) (hm shared))\n";
    let expanded_first = format!(
        "{library}(define (bump) (bump-count!))\n(bump)\n(define count 100)\n(bump)\n\
         (list (get-count) count)"
    );
    let defined_first = format!(
        "{library}(define count 100)\n(define (bump) (bump-count!))\n(bump)\n\
         (list (get-count) count)"
    );
    for vm in [true, false] {
        assert_eq!(
            answer(&expanded_first, vm),
            "(2 100)",
            "`(1 101)` is the template's reference following the program's definition"
        );
        assert_eq!(answer(&defined_first, vm), "(1 100)");
    }
}

/// A program's definition over an imported name is not the binding a
/// library macro's *literal* of that name means (#450) — the literal-side
/// twin of the test above. chibi 0.12 and Gauche 0.9.15 answer `2`, `lit` and
/// `1`, measured 2026-09-22.
///
/// Two identifiers spelled alike and reaching no local binding were matched
/// whatever global each reached, so after `(define else #f)` the `(else 1)`
/// below was still `cond`'s else clause and answered `1`. The literal now
/// matches when the two reach one location (`Environment::binding_location`),
/// which the program's `else` stops doing once it defines over the import.
///
/// The other two are the controls. A macro the program defines itself sees
/// the program's own `else` as its literal's binding, before the definition
/// and after it, in both oracles: `lit`. And a program that never defines
/// `else` reaches the imported keyword, as it always did.
#[test]
fn a_definition_over_an_import_is_not_a_library_macros_literal() {
    let over_the_import = "(import (scheme base))\n(define else #f)\n\
                           (cond (#f 0) (else 1) (#t 2))";
    let the_programs_own_macro = "(import (scheme base))\n\
                                  (define-syntax m\n  \
                                  (syntax-rules (else) ((_ else) 'lit) ((_ x) 'var)))\n\
                                  (define else #f)\n(m else)";
    let never_defined = "(import (scheme base))\n(cond (#f 0) (else 1))";
    for vm in [true, false] {
        assert_eq!(
            answer(over_the_import, vm),
            "2",
            "`1` is the program's `else` taken for `cond`'s keyword"
        );
        assert_eq!(answer(the_programs_own_macro, vm), "lit");
        assert_eq!(answer(never_defined, vm), "1");
    }
}

